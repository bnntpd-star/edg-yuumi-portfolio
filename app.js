let currentSpellKey = 'r';

function selectSpell(key) {
  currentSpellKey = key;
  playSfx('spell');

  document.querySelectorAll('.spell-btn').forEach(btn => {
    if (btn.getAttribute('data-spell') === key) {
      btn.classList.add('ring-2', 'ring-cyan-400', 'bg-cyan-950/80', 'scale-105');
      btn.classList.remove('bg-slate-900/60');
    } else {
      btn.classList.remove('ring-2', 'ring-cyan-400', 'bg-cyan-950/80', 'scale-105');
      btn.classList.add('bg-slate-900/60');
    }
  });

  updateSpellDetails();
}

function updateSpellDetails() {
  const data = spellsData[currentSpellKey];
  if (!data) return;

  const titleEl = document.getElementById('spellDetailTitle');
  const cdEl = document.getElementById('spellDetailCd');
  const loreEl = document.getElementById('spellDetailLore');
  const metricsEl = document.getElementById('spellDetailMetrics');

  if (titleEl) titleEl.textContent = data.name[currentLang] || data.name.en;
  if (cdEl) cdEl.textContent = data.cooldown;
  if (loreEl) loreEl.textContent = data.lore[currentLang] || data.lore.en;

  if (metricsEl) {
    metricsEl.innerHTML = data.metrics.map(m => `
      <div class="bg-slate-900/80 border border-cyan-500/30 rounded-lg p-3">
        <div class="text-xs text-cyan-300/80 uppercase font-semibold">${m.label[currentLang] || m.label.en}</div>
        <div class="text-xl font-bold text-white mt-1">${m.val}</div>
      </div>
    `).join('');
  }
}

// Audio Player Controller
function initAudioControls() {
  const toggleBtn = document.getElementById('audioToggleBtn');
  const volumeSlider = document.getElementById('volumeSlider');
  const equalizer = document.getElementById('equalizerBars');
  const audioText = document.getElementById('audioStatusText');

  if (toggleBtn) {
    toggleBtn.addEventListener('click', () => {
      toggleMusic();
    });
  }

  if (volumeSlider) {
    volumeSlider.addEventListener('input', (e) => {
      const vol = e.target.value;
      if (ytPlayer && ytPlayer.setVolume) {
        ytPlayer.setVolume(vol);
      }
    });
  }
}

function toggleMusic() {
  playSfx('click');
  const equalizer = document.getElementById('equalizerBars');
  const icon = document.getElementById('audioIcon');
  const statusBadge = document.getElementById('audioStatusBadge');

  if (isAudioPlaying) {
    pauseMusic();
  } else {
    playMusic();
  }
}

function playMusic() {
  if (ytPlayer && ytPlayer.playVideo) {
    ytPlayer.playVideo();
  }
  isAudioPlaying = true;
  const equalizer = document.getElementById('equalizerBars');
  const icon = document.getElementById('audioIcon');
  const statusBadge = document.getElementById('audioStatusBadge');

  if (equalizer) equalizer.classList.remove('equalizer-paused');
  if (icon) icon.innerHTML = `<path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M10 9v6m4-6v6m7-3a9 9 0 11-18 0 9 9 0 0118 0z" />`;
  if (statusBadge) {
    statusBadge.textContent = "PLAYING";
    statusBadge.className = "text-[11px] font-bold px-2 py-0.5 rounded bg-cyan-500/20 text-cyan-300 border border-cyan-500/40 animate-pulse";
  }
}

function pauseMusic() {
  if (ytPlayer && ytPlayer.pauseVideo) {
    ytPlayer.pauseVideo();
  }
  isAudioPlaying = false;
  const equalizer = document.getElementById('equalizerBars');
  const icon = document.getElementById('audioIcon');
  const statusBadge = document.getElementById('audioStatusBadge');

  if (equalizer) equalizer.classList.add('equalizer-paused');
  if (icon) icon.innerHTML = `<path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M14.752 11.168l-3.197-2.132A1 1 0 0010 9.87v4.263a1 1 0 001.555.832l3.197-2.132a1 1 0 000-1.664z" /><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M21 12a9 9 0 11-18 0 9 9 0 0118 0z" />`;
  if (statusBadge) {
    statusBadge.textContent = "PAUSED";
    statusBadge.className = "text-[11px] font-bold px-2 py-0.5 rounded bg-slate-700/50 text-slate-400 border border-slate-600";
  }
}

// YouTube Iframe API callback
window.onYouTubeIframeAPIReady = function() {
  ytPlayer = new YT.Player('youtubePlayerHidden', {
    height: '0',
    width: '0',
    videoId: 'mH06l-4P3aU', // Burn It All Down - Worlds 2021
    playerVars: {
      autoplay: 0,
      loop: 1,
      playlist: 'mH06l-4P3aU',
      controls: 0,
      modestbranding: 1
    },
    events: {
      'onReady': onPlayerReady,
      'onStateChange': onPlayerStateChange
    }
  });
};

function onPlayerReady(event) {
  event.target.setVolume(75);
}

function onPlayerStateChange(event) {
  if (event.data === YT.PlayerState.PLAYING) {
    isAudioPlaying = true;
    const equalizer = document.getElementById('equalizerBars');
    if (equalizer) equalizer.classList.remove('equalizer-paused');
  } else if (event.data === YT.PlayerState.PAUSED || event.data === YT.PlayerState.ENDED) {
    isAudioPlaying = false;
    const equalizer = document.getElementById('equalizerBars');
    if (equalizer) equalizer.classList.add('equalizer-paused');
  }
}

